USE `tz_gold`;
DROP TABLE IF EXISTS `g_ai_stock_daily`;
DROP TABLE IF EXISTS `g_fin_rpt_mkt_smry`;

CREATE TABLE `g_ai_stock_daily` (
  `stock_cd` CHAR(6) NOT NULL COMMENT '종목 코드',
  `trd_dt` DATE NOT NULL COMMENT '거래 일자',
  `corp_cd` CHAR(8) COMMENT '기업 코드',
  `mkt_cd` VARCHAR(50) NOT NULL COMMENT '시장 코드',
  `open_prc` DECIMAL(18,4) NOT NULL COMMENT '시가 가격',
  `high_prc` DECIMAL(18,4) NOT NULL COMMENT '고가 가격',
  `low_prc` DECIMAL(18,4) NOT NULL COMMENT '저가 가격',
  `close_prc` DECIMAL(18,4) NOT NULL COMMENT '종가 가격',
  `trd_qty` BIGINT NOT NULL COMMENT '거래 수량',
  `close_rtn_rt` DECIMAL(12,8) COMMENT '종가 수익률(전 관측일 대비)',
  `idx_close_prc` DECIMAL(18,4) COMMENT '지수 종가 가격',
  `idx_rtn_rt` DECIMAL(12,8) COMMENT '지수 수익률(전 관측일 대비)',
  `indv_net_buy_qty` BIGINT COMMENT '개인 순매수 수량',
  `frgn_net_buy_qty` BIGINT COMMENT '외국인 순매수 수량',
  `inst_net_buy_qty` BIGINT COMMENT '기관 순매수 수량',
  `other_corp_net_buy_qty` BIGINT COMMENT '기타법인 순매수 수량',
  `frgn_hold_rt` DECIMAL(12,8) COMMENT '외국인 보유 율',
  `cfd_buy_bal_rt` DECIMAL(12,8) COMMENT 'CFD 매수 잔고 율',
  `invstr_exist_yn` CHAR(1) NOT NULL COMMENT '수급 존재 여부',
  `fin_avail_yn` CHAR(1) NOT NULL COMMENT '재무 가용 여부',
  `fin_rpt_id` VARCHAR(64) COMMENT '재무 보고서 식별자',
  `fin_bsns_yr` CHAR(4) COMMENT '재무 사업 연도',
  `fin_rpt_cd` VARCHAR(50) COMMENT '재무 보고서 코드',
  `fin_fs_div_cd` VARCHAR(50) COMMENT '재무 재무제표 구분 코드',
  `dscl_dt` DATE COMMENT '공시 일자',
  `dscl_elps_day_cnt` INT COMMENT '공시 경과 일 건수',
  `rev_ytd_amt` DECIMAL(20,0) COMMENT '매출 누적 금액',
  `op_prft_ytd_amt` DECIMAL(20,0) COMMENT '영업 이익 누적 금액',
  `net_incm_ytd_amt` DECIMAL(20,0) COMMENT '순이익 누적 금액',
  `op_cf_ytd_amt` DECIMAL(20,0) COMMENT '영업 현금흐름 누적 금액',
  `tot_asst_amt` DECIMAL(20,0) COMMENT '총 자산 금액',
  `tot_liab_amt` DECIMAL(20,0) COMMENT '총 부채 금액',
  `tot_eqty_amt` DECIMAL(20,0) COMMENT '총 자본 금액',
  `pipln_ver` VARCHAR(80) NOT NULL COMMENT '파이프라인 버전',
  PRIMARY KEY (`stock_cd`, `trd_dt`),
  CONSTRAINT `ck_g_ai_stock_daily_stock_cd` CHECK (REGEXP_LIKE(`stock_cd`, '^[0-9]{6}$', 'c')),
  CONSTRAINT `ck_g_ai_stock_daily_corp_cd` CHECK (`corp_cd` IS NULL OR REGEXP_LIKE(`corp_cd`, '^[0-9]{8}$', 'c')),
  CONSTRAINT `ck_g_ai_stock_daily_mkt_cd` CHECK (`mkt_cd` IN ('KOSPI','KOSDAQ')),
  CONSTRAINT `ck_g_ai_stock_daily_open_prc` CHECK (`open_prc` >= 0),
  CONSTRAINT `ck_g_ai_stock_daily_high_prc` CHECK (`high_prc` >= 0),
  CONSTRAINT `ck_g_ai_stock_daily_low_prc` CHECK (`low_prc` >= 0),
  CONSTRAINT `ck_g_ai_stock_daily_close_prc` CHECK (`close_prc` >= 0),
  CONSTRAINT `ck_g_ai_stock_daily_idx_close_prc` CHECK (`idx_close_prc` IS NULL OR `idx_close_prc` >= 0),
  CONSTRAINT `ck_g_ai_stock_daily_invstr_exist_yn` CHECK (`invstr_exist_yn` IN ('Y','N')),
  CONSTRAINT `ck_g_ai_stock_daily_fin_avail_yn` CHECK (`fin_avail_yn` IN ('Y','N')),
  CONSTRAINT `ck_g_ai_stock_daily_fin_bsns_yr` CHECK (`fin_bsns_yr` IS NULL OR REGEXP_LIKE(`fin_bsns_yr`, '^[0-9]{4}$', 'c')),
  CONSTRAINT `ck_g_ai_stock_daily_fin_rpt_cd` CHECK (`fin_rpt_cd` IS NULL OR `fin_rpt_cd` IN ('11013','11012','11014','11011')),
  CONSTRAINT `ck_g_ai_stock_daily_fin_fs_div_cd` CHECK (`fin_fs_div_cd` IS NULL OR `fin_fs_div_cd` IN ('CFS','OFS')),
  CONSTRAINT `ck_g_ai_stock_daily_dscl_elps_day_cnt` CHECK (`dscl_elps_day_cnt` IS NULL OR `dscl_elps_day_cnt` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='AI 학습용 종목 일별 데이터셋 | 단위: 종목·거래일당 1행(가격 기준) | 논리FK: stock_cd->s_stock.stock_cd; fin_rpt_id->s_fin_rpt.fin_rpt_id';

CREATE TABLE `g_fin_rpt_mkt_smry` (
  `fin_rpt_id` VARCHAR(64) NOT NULL COMMENT '재무 보고서 식별자',
  `corp_cd` CHAR(8) NOT NULL COMMENT '기업 코드',
  `stock_cd` CHAR(6) NOT NULL COMMENT '종목 코드',
  `bsns_yr` CHAR(4) NOT NULL COMMENT '사업 연도',
  `rpt_cd` VARCHAR(50) NOT NULL COMMENT '보고서 코드',
  `fs_div_cd` VARCHAR(50) NOT NULL COMMENT '재무제표 구분 코드',
  `prd_start_dt` DATE NOT NULL COMMENT '기간 시작 일자',
  `prd_end_dt` DATE NOT NULL COMMENT '기간 종료 일자',
  `same_prd_cmpr_elig_yn` CHAR(1) NOT NULL COMMENT '동일 기간 비교 적격 여부',
  `trd_day_cnt` INT NOT NULL COMMENT '거래 일 건수',
  `full_cvrg_yn` CHAR(1) NOT NULL COMMENT '기간 전체 커버리지 여부',
  `first_close_prc` DECIMAL(18,4) COMMENT '첫 종가 가격',
  `last_close_prc` DECIMAL(18,4) COMMENT '마지막 종가 가격',
  `prd_rtn_rt` DECIMAL(12,8) COMMENT '기간 수익률',
  `frgn_net_buy_qty` BIGINT COMMENT '외국인 순매수 수량(기간 합)',
  `inst_net_buy_qty` BIGINT COMMENT '기관 순매수 수량(기간 합)',
  `indv_net_buy_qty` BIGINT COMMENT '개인 순매수 수량(기간 합)',
  `rev_ytd_amt` DECIMAL(20,0) COMMENT '매출 누적 금액',
  `op_prft_ytd_amt` DECIMAL(20,0) COMMENT '영업 이익 누적 금액',
  `op_cf_ytd_amt` DECIMAL(20,0) COMMENT '영업 현금흐름 누적 금액',
  `pipln_ver` VARCHAR(80) NOT NULL COMMENT '파이프라인 버전',
  PRIMARY KEY (`fin_rpt_id`),
  CONSTRAINT `ck_g_fin_rpt_mkt_smry_corp_cd` CHECK (REGEXP_LIKE(`corp_cd`, '^[0-9]{8}$', 'c')),
  CONSTRAINT `ck_g_fin_rpt_mkt_smry_stock_cd` CHECK (REGEXP_LIKE(`stock_cd`, '^[0-9]{6}$', 'c')),
  CONSTRAINT `ck_g_fin_rpt_mkt_smry_bsns_yr` CHECK (REGEXP_LIKE(`bsns_yr`, '^[0-9]{4}$', 'c')),
  CONSTRAINT `ck_g_fin_rpt_mkt_smry_rpt_cd` CHECK (`rpt_cd` IN ('11013','11012','11014','11011')),
  CONSTRAINT `ck_g_fin_rpt_mkt_smry_fs_div_cd` CHECK (`fs_div_cd` IN ('CFS','OFS')),
  CONSTRAINT `ck_g_fin_rpt_mkt_smry_same_prd_cmpr_elig_yn` CHECK (`same_prd_cmpr_elig_yn` IN ('Y','N')),
  CONSTRAINT `ck_g_fin_rpt_mkt_smry_trd_day_cnt` CHECK (`trd_day_cnt` >= 0),
  CONSTRAINT `ck_g_fin_rpt_mkt_smry_full_cvrg_yn` CHECK (`full_cvrg_yn` IN ('Y','N')),
  CONSTRAINT `ck_g_fin_rpt_mkt_smry_first_close_prc` CHECK (`first_close_prc` IS NULL OR `first_close_prc` >= 0),
  CONSTRAINT `ck_g_fin_rpt_mkt_smry_last_close_prc` CHECK (`last_close_prc` IS NULL OR `last_close_prc` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='재무 보고기간 시장 요약 | 단위: 재무 보고서당 1행 | 논리FK: fin_rpt_id->s_fin_rpt.fin_rpt_id';
